const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {syncXmlInstallments}=require('../dist/services/invoiceInstallments.js');
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE invoice_installments(id TEXT PRIMARY KEY,invoice_id TEXT,company_id TEXT,tipo TEXT,numero_fatura TEXT,numero_parcela TEXT,data_vencimento TEXT,valor REAL,status TEXT,forma_pagamento TEXT,fornecedor_cliente_nome TEXT,fornecedor_cliente_cnpj TEXT,created_at TEXT)`);
const p={naturezaOperacao:'Compra',emitente:{razaoSocial:'Fixture isolada',cnpjCpf:'00000000000000'},destinatario:{},pagamentos:[{forma:'PIX',valor:100}],duplicatas:[]};
syncXmlInstallments(db,'note','company','entrada',p);
assert.equal(db.prepare('SELECT count(*) n FROM invoice_installments').get().n,0,'No invented due date or payable without XML duplicatas');
p.duplicatas=[{numero:'01',vencimento:'2026-10-01',valor:60},{numero:'02',vencimento:'2026-11-01',valor:40}];
syncXmlInstallments(db,'note','company','entrada',p);
syncXmlInstallments(db,'note','company','entrada',p);
assert.equal(db.prepare('SELECT count(*) n FROM invoice_installments').get().n,2);
assert.equal(db.prepare('SELECT forma_pagamento FROM invoice_installments LIMIT 1').get().forma_pagamento,'PIX');
db.exec("UPDATE invoice_installments SET status='pago' WHERE numero_parcela='01'");
const settled=db.prepare("SELECT * FROM invoice_installments WHERE numero_parcela='01'").get();
p.duplicatas[0].valor=70;
syncXmlInstallments(db,'note','company','entrada',p);
assert.deepEqual(db.prepare('SELECT * FROM invoice_installments WHERE id=?').get(settled.id),settled,'Paid history must not be reset by ingestion');
p.duplicatas[1].vencimento='';
assert.throws(()=>syncXmlInstallments(db,'note','company','entrada',p),/vencimento/);
assert.equal(db.prepare('SELECT count(*) n FROM invoice_installments').get().n,2);
db.close();console.log('PASS: real XML installments, no inferred date, repeat-safe ingestion and preserved paid history.');
